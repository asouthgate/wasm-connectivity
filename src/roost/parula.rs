fn interpolate(stops: &[[f64; 3]; 64], n: usize) -> Vec<[f64; 3]> {
    if n == 1 {
        return vec![stops[0]];
    }
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let x = (i as f64) / ((n - 1) as f64) * 63.0;
        let idx = (x.floor() as usize).min(62);
        let frac = x - idx as f64;
        let a = stops[idx];
        let b = stops[idx + 1];
        out.push([
            a[0] + (b[0] - a[0]) * frac,
            a[1] + (b[1] - a[1]) * frac,
            a[2] + (b[2] - a[2]) * frac,
        ]);
    }
    out
}

/// Return an `n`-entry parula colormap as `[r, g, b]` triplets in 0..1.
///
/// `version`: `"new"` = R2019b+ (default), `"old"` = R2014b..R2019a.
pub fn parula(n: usize, version: &str) -> Vec<[f64; 3]> {
    let stops = if version == "old" { &OLD_STOPS } else { &NEW_STOPS };
    interpolate(stops, n)
}

/// Return an `n`-entry parula colormap as 8-bit `[r, g, b]` triplets.
pub fn parula_u8(n: usize, version: &str) -> Vec<[u8; 3]> {
    parula(n, version)
        .into_iter()
        .map(|c| {
            [
                (c[0].clamp(0.0, 1.0) * 255.0).round() as u8,
                (c[1].clamp(0.0, 1.0) * 255.0).round() as u8,
                (c[2].clamp(0.0, 1.0) * 255.0).round() as u8,
            ]
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::parula;

    #[test]
    fn endpoints() {
        let p = parula(256, "new");
        assert_eq!(p.len(), 256);
        assert!((p[0][0] - 0.2422).abs() < 1e-12);
        assert!((p[255][2] - 0.0805).abs() < 1e-12);
        // Monotone-ish sanity: last entry is the yellow end.
        assert!(p[255][0] > 0.9 && p[255][1] > 0.9 && p[255][2] < 0.1);
    }
}
